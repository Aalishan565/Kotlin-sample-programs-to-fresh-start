package _0_kotlin_basics

/**
 * 1HelloKotlin.kt
 * Demonstrates the entry point of a Kotlin application.
 *
 * Key Concepts:
 * 1. Top-level functions: Kotlin functions can exist outside of a class.
 * 2. `main()` function: The mandatory entry point required by the JVM/Kotlin runtime.
 * 3. `println()`: Standard Kotlin function to print a line to standard output (wraps System.out.println).
 */
fun main() {
    println("--- Kotlin Entry Point & Output ---")
    println("Hello from Kotlin!")
    println("Welcome to Kotlin Programming Basic Concepts.")
}
